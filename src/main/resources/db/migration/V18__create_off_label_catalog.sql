CREATE TABLE off_labels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_tag TEXT NOT NULL UNIQUE,
    locale_key VARCHAR(35) NOT NULL
);

CREATE TABLE product_off_labels (
    product_id BIGINT NOT NULL REFERENCES product_open_food_facts(product_id) ON DELETE CASCADE,
    label_id BIGINT NOT NULL REFERENCES off_labels(id),
    PRIMARY KEY (product_id, label_id)
);

CREATE INDEX idx_product_off_labels_label ON product_off_labels(label_id);
