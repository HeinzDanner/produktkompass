CREATE TABLE product_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    description VARCHAR(2000) NOT NULL,
    target_field VARCHAR(30),
    provenance VARCHAR(30),
    submitted_at TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    moderated_by VARCHAR(255),
    moderated_at TIMESTAMP,
    CONSTRAINT ck_product_reports_status CHECK (status IN ('OPEN', 'REVIEWED', 'CLOSED')),
    CONSTRAINT ck_product_reports_target CHECK (target_field IN
        ('NAME', 'BRAND', 'COMPANY', 'INGREDIENTS', 'NUTRITION', 'LABELS', 'PACKAGING', 'ORIGIN', 'OTHER')),
    CONSTRAINT ck_product_reports_provenance CHECK (provenance IN ('APP_CATALOG', 'OPEN_FOOD_FACTS'))
);

CREATE INDEX idx_product_reports_queue ON product_reports(status, submitted_at, id);
CREATE INDEX idx_product_reports_submitted ON product_reports(submitted_at, id);
CREATE INDEX idx_product_reports_product ON product_reports(product_id);
