CREATE TABLE retailer_catalogs (
    code VARCHAR(32) PRIMARY KEY,
    display_name VARCHAR(100) NOT NULL,
    source_kind VARCHAR(30) NOT NULL,
    imported_at TIMESTAMP,
    CONSTRAINT ck_retailer_catalog_source CHECK (source_kind IN ('SYNTHETIC', 'USER_SUPPLIED'))
);

CREATE TABLE retailer_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    catalog_code VARCHAR(32) NOT NULL REFERENCES retailer_catalogs(code) ON DELETE CASCADE,
    external_id VARCHAR(500) NOT NULL,
    name VARCHAR(500) NOT NULL,
    brand VARCHAR(255),
    category_path VARCHAR(1000),
    package_size VARCHAR(100),
    price DECIMAL(10, 2),
    previous_price DECIMAL(10, 2),
    discount_percent DECIMAL(6, 2),
    product_url VARCHAR(1000),
    image_url VARCHAR(1000),
    description VARCHAR(4000),
    preference_tags VARCHAR(1000),
    allergens VARCHAR(1000),
    traces VARCHAR(1000),
    availability VARCHAR(255),
    imported_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_retailer_product_external UNIQUE (catalog_code, external_id),
    CONSTRAINT ck_retailer_product_price CHECK (price IS NULL OR price >= 0),
    CONSTRAINT ck_retailer_product_previous_price CHECK (previous_price IS NULL OR previous_price >= 0),
    CONSTRAINT ck_retailer_product_discount CHECK (discount_percent IS NULL OR discount_percent >= 0)
);

CREATE INDEX idx_retailer_products_catalog ON retailer_products(catalog_code, name, id);

CREATE TABLE retailer_product_match_cache (
    owner_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    source_product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    catalog_code VARCHAR(32) NOT NULL REFERENCES retailer_catalogs(code) ON DELETE CASCADE,
    retailer_product_id BIGINT REFERENCES retailer_products(id) ON DELETE SET NULL,
    updated_at TIMESTAMP NOT NULL,
    PRIMARY KEY (owner_id, source_product_id, catalog_code)
);

CREATE TABLE retailer_shopping_lists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    catalog_code VARCHAR(32) NOT NULL REFERENCES retailer_catalogs(code),
    name VARCHAR(120) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_retailer_shopping_lists_owner ON retailer_shopping_lists(owner_id, created_at, id);

CREATE TABLE retailer_shopping_list_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    list_id BIGINT NOT NULL REFERENCES retailer_shopping_lists(id) ON DELETE CASCADE,
    source_product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
    retailer_product_id BIGINT REFERENCES retailer_products(id) ON DELETE SET NULL,
    source_product_name VARCHAR(255) NOT NULL,
    retailer_product_name VARCHAR(500) NOT NULL,
    retailer_brand VARCHAR(255),
    package_size VARCHAR(100),
    selection_kind VARCHAR(20) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price DECIMAL(10, 2),
    product_url VARCHAR(1000),
    CONSTRAINT ck_retailer_list_item_quantity CHECK (quantity > 0),
    CONSTRAINT ck_retailer_list_item_selection CHECK (selection_kind IN ('CATALOG', 'MANUAL'))
);

CREATE INDEX idx_retailer_list_items_list ON retailer_shopping_list_items(list_id, id);
