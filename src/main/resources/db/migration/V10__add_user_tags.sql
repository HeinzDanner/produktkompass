CREATE TABLE user_tags
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(50) NOT NULL,
    user_id    BIGINT      NOT NULL,
    created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_user_tags_user
        FOREIGN KEY (user_id) REFERENCES app_users (id),
    -- Derselbe Benutzer darf denselben Tag-Namen nicht doppelt anlegen.
    CONSTRAINT uq_user_tags_user_name UNIQUE (user_id, name)
);

CREATE TABLE user_tag_products
(
    user_tag_id BIGINT NOT NULL,
    product_id  BIGINT NOT NULL,
    PRIMARY KEY (user_tag_id, product_id),
    CONSTRAINT fk_user_tag_products_tag
        FOREIGN KEY (user_tag_id) REFERENCES user_tags (id),
    CONSTRAINT fk_user_tag_products_product
        FOREIGN KEY (product_id) REFERENCES products (id)
);

CREATE TABLE user_tag_brands
(
    user_tag_id BIGINT NOT NULL,
    brand_id    BIGINT NOT NULL,
    PRIMARY KEY (user_tag_id, brand_id),
    CONSTRAINT fk_user_tag_brands_tag
        FOREIGN KEY (user_tag_id) REFERENCES user_tags (id),
    CONSTRAINT fk_user_tag_brands_brand
        FOREIGN KEY (brand_id) REFERENCES brands (id)
);
